/* ==========================================================================================================
   Addendum 46 - PO Pricing Foundation: ROLLBACK of Demand migration 20261017172349_A46_PricingFoundation
   (register A46-0072..0079; analysis E-14).  Run against the Demand database (SMSGlobal or a copy).

   Equivalent to `dotnet ef database update 20261017132713_A45_SupplierPricelists --context DemandDbContext`
   (the migration's Down is the same hand-guarded, idempotent SQL), for DBAs who prefer a script.

   READ FIRST - what a rollback costs:
     * UnitPrice (PO lines) and AutoGeneratedPrice (POs) go back to decimal(18,2): a price held at 4dp
       (12.3456) is ROUNDED to the cent (12.35). Take a backup / run the CHECK below first.
     * Lines priced by a blanket order (PriceSource = 4) are set to Manual (0) so the old CHECK can hold.
     * OrderDate and the four conversion-audit columns are dropped with their data.
     * After rolling the SCHEMA back, the A46 application code must not be running (it maps the dropped columns).
   Every statement is guarded, so the script can be run twice.
   ========================================================================================================== */

-- 0. What would be rounded? (informational - review before continuing)
IF COL_LENGTH('demand.purchase_order_lines', 'UnitPrice') IS NOT NULL
    SELECT COUNT(*) AS PoLinePricesThatLose4dp
    FROM demand.purchase_order_lines
    WHERE UnitPrice <> ROUND(UnitPrice, 2);

-- 1. M8: conversion audit columns
IF COL_LENGTH('demand.purchase_order_lines', 'ExchangeRateDate')     IS NOT NULL ALTER TABLE demand.purchase_order_lines DROP COLUMN ExchangeRateDate;
IF COL_LENGTH('demand.purchase_order_lines', 'ExchangeRateUsed')     IS NOT NULL ALTER TABLE demand.purchase_order_lines DROP COLUMN ExchangeRateUsed;
IF COL_LENGTH('demand.purchase_order_lines', 'OriginalCurrencyPrice') IS NOT NULL ALTER TABLE demand.purchase_order_lines DROP COLUMN OriginalCurrencyPrice;
IF COL_LENGTH('demand.purchase_order_lines', 'OriginalCurrencyId')   IS NOT NULL ALTER TABLE demand.purchase_order_lines DROP COLUMN OriginalCurrencyId;
GO

-- 2. M5: PriceSource back to 0..3
IF COL_LENGTH('demand.purchase_order_lines', 'PriceSource') IS NOT NULL
    EXEC('UPDATE demand.purchase_order_lines SET PriceSource = 0 WHERE PriceSource = 4');
IF EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_POLines_PriceSource' AND parent_object_id = OBJECT_ID('demand.purchase_order_lines') AND definition LIKE '%4%')
    ALTER TABLE demand.purchase_order_lines DROP CONSTRAINT CK_POLines_PriceSource;
IF NOT EXISTS (SELECT 1 FROM sys.check_constraints WHERE name = 'CK_POLines_PriceSource' AND parent_object_id = OBJECT_ID('demand.purchase_order_lines'))
    ALTER TABLE demand.purchase_order_lines ADD CONSTRAINT CK_POLines_PriceSource CHECK (PriceSource IN (0, 1, 2, 3));
GO

-- 3. M4: prices back to 2dp (ROUNDS 4dp values)
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_order_lines') AND name = 'UnitPrice' AND (precision <> 18 OR scale <> 2))
    ALTER TABLE demand.purchase_order_lines ALTER COLUMN UnitPrice decimal(18,2) NOT NULL;
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_orders') AND name = 'AutoGeneratedPrice' AND (precision <> 18 OR scale <> 2))
    ALTER TABLE demand.purchase_orders ALTER COLUMN AutoGeneratedPrice decimal(18,2) NULL;
GO

-- 4. M9/M10: OrderDate (the backfill from CreatedDate is lost with the column)
DECLARE @df sysname = (SELECT dc.name FROM sys.default_constraints dc WHERE dc.parent_object_id = OBJECT_ID('demand.purchase_orders')
                       AND dc.parent_column_id = COLUMNPROPERTY(OBJECT_ID('demand.purchase_orders'), 'OrderDate', 'ColumnId'));
IF @df IS NOT NULL EXEC('ALTER TABLE demand.purchase_orders DROP CONSTRAINT [' + @df + ']');
IF COL_LENGTH('demand.purchase_orders', 'OrderDate') IS NOT NULL ALTER TABLE demand.purchase_orders DROP COLUMN OrderDate;
GO

