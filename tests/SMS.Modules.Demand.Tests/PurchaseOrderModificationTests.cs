    // ── Split ────────────────────────────────────────────────────────────────

    private static SplitPoRequest Split(Harness h, decimal qty = 15m, decimal? price = null) => new()
    {
        LineUuid = Guid.Empty, Quantity = qty, SupplierId = h.SupplierB, SupplierName = "Vendor B", UnitPrice = price
    };

    private static async Task<SplitPoRequest> SplitOf(Harness h, decimal qty = 15m, decimal? price = null)
    {
        var req = Split(h, qty, price);
        req.LineUuid = (await Po(h)).Lines.Single().UUID;
        return req;
    }

    [Fact]
    public async Task A_split_moves_the_quantity_to_a_new_draft_po_for_the_other_supplier()
    {
        var h = await NewHarness();

        var result = await h.Repo.SplitAsync(h.PoUuid, await SplitOf(h, qty: 15m), Editor);

        var source = await Po(h);
        source.Lines.Single().Quantity.Should().Be(25m);
        source.Lines.Single().LineTotal.Should().Be(625m);
        source.TotalAmount.Should().Be(625m);
        source.SupplierId.Should().Be(h.SupplierA);
        source.Status.Should().Be("DRAFT");

        var split = await h.Db.PurchaseOrders.AsNoTracking().Include(p => p.Lines).SingleAsync(p => p.UUID == result.NewPoUuid);
        split.PoNumber.Should().Be(result.NewPoNumber).And.NotBe(source.PoNumber);
        split.Status.Should().Be("DRAFT");
        split.SupplierId.Should().Be(h.SupplierB);
        split.SupplierName.Should().Be("Vendor B");
        split.CreatedBy.Should().Be(Editor);
        var line = split.Lines.Should().ContainSingle().Subject;
        (line.VariantUuid, line.ItemDescription, line.UnitOfMeasure).Should().Be((h.Variant, Cable, source.Lines.Single().UnitOfMeasure));
        line.Quantity.Should().Be(15m);
        line.UnitPrice.Should().Be(25m, "the line's own price when the request names none");
        split.TotalAmount.Should().Be(375m);
    }

