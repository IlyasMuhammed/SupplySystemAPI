    private const int Creator = 11;
    private const int Editor = 22;
    private const string Cable = "4mm cable";

    private sealed record Harness(
        DemandDbContext Db, PurchaseOrderRepository Repo, Guid OrgId,
        Guid SupplierA, Guid SupplierB, Guid Variant, Guid PoUuid, Guid OrderUuid, Guid LineUuid, int PoId);

    // A CONFIRMED order selling 100 at 40, 40 of which is short; the system bought the 40 at 25 from A.
    private static async Task<Harness> NewHarness(string source = "BACK_TO_BACK", bool linked = true, string status = "DRAFT")
    {
        var orgId = Guid.NewGuid();
        var db = new DemandDbContext(
            new DbContextOptionsBuilder<DemandDbContext>().UseInMemoryDatabase(Guid.NewGuid().ToString()).Options,
            new StaticTenantContext { OrganizationId = orgId });
        var repo = new PurchaseOrderRepository(db, NullLogger<PurchaseOrderRepository>.Instance);

        var variant = Guid.NewGuid();
        var supplierA = Guid.NewGuid();
        var supplierB = Guid.NewGuid();

        var order = new SaleOrder
        {
            SoNumber = "SO-2026-00042", PartnerId = Guid.NewGuid(), OrderDate = DateTime.UtcNow.Date,
            CurrencyId = Guid.NewGuid(), Status = "CONFIRMED", DeliveryMode = "SELF_PICKUP", CreatedBy = Creator,
            TraceId = Guid.NewGuid(),
            Lines = { new SaleOrderLine { VariantUuid = variant, Quantity = 100m, UnitPrice = 40m, LineTotal = 4000m,
                                          FulfillmentMode = "BACK_TO_BACK", DeficitQty = 40m, Status = "OPEN",
                                          Margin = 15m, MarginPercent = 37.5m } }
        };
        db.SaleOrders.Add(order);
        await db.SaveChangesAsync();
        var line = order.Lines.Single();

        var created = await repo.CreateFromSaleOrderDeficitAsync(new SaleOrderDeficitPo(
            source, "DRAFT", order.TraceId, order.Id, line.Id, order.SoNumber, supplierA, "Vendor A", variant, 40m, 25m, null), Creator);

        var po = await db.PurchaseOrders.Include(p => p.Lines).SingleAsync(p => p.UUID == created.Uuid);
        po.Lines.Single().ItemDescription = Cable;
        po.Status = status;
        if (!linked)
        {
            po.Source = "MANUAL"; po.LinkedSoId = null; po.LinkedSoLineId = null;
            po.AutoGeneratedQty = null; po.AutoGeneratedPrice = null; po.AutoSelectedSupplierId = null;
        }
        else
        {
            line.LinkedPoId = po.Id;
            line.SelectedSupplierId = supplierA;
        }
        await db.SaveChangesAsync();
        db.ChangeTracker.Clear();

        return new Harness(db, repo, orgId, supplierA, supplierB, variant, po.UUID, order.UUID, line.UUID, po.Id);
    }

    private static PatchPoRequest Lines(Harness h, decimal qty, decimal price, params CreatePoLineRequest[] extra) => new()
    {
        Lines =
        [
            new CreatePoLineRequest { VariantUuid = h.Variant, ItemDescription = Cable, UnitOfMeasure = "PC", Quantity = qty, UnitPrice = price },
            .. extra
        ]
    };

    private static Task<PurchaseOrder> Po(Harness h) =>
        h.Db.PurchaseOrders.AsNoTracking().Include(p => p.Lines).SingleAsync(p => p.UUID == h.PoUuid);

    private static Task<SaleOrderLine> SoLine(Harness h) =>
        h.Db.SaleOrderLines.AsNoTracking().SingleAsync(l => l.UUID == h.LineUuid);

