/// <summary>
/// A46 M4/M5/M8/M9/M10 (A46-0003..0006, 0021..0023, 0032..0034, 0070..0081, 0084, 0209) on real SQL Server (LocalDB): the guarded
/// A46_PricingFoundation goes up, down and up, re-runs on a database that already has it without touching edited data, backfills
/// OrderDate from CreatedDate, widens prices without loss, accepts price source 4, stores the conversion audit exactly, and
/// produces the model the code maps.
/// </summary>
public sealed class A46PricingMigrationTests : IAsyncLifetime
{
    private const string Server = @"Server=(localdb)\MSSQLLocalDB;Trusted_Connection=True;TrustServerCertificate=True;";
    private readonly string _connection = $"{Server}Database=A46_DEM_Migr_{Guid.NewGuid():N};";

    private DemandDbContext NewContext(Guid? org = null) => new(
        new DbContextOptionsBuilder<DemandDbContext>().UseSqlServer(_connection).Options,
        new StaticTenantContext { OrganizationId = org ?? Guid.NewGuid() });

    public Task InitializeAsync() => Task.CompletedTask;

    public async Task DisposeAsync()
    {
        await using var db = NewContext();
        await db.Database.EnsureDeletedAsync();
    }

    private static async Task<T> Scalar<T>(DemandDbContext db, string sql)
    {
        var conn = db.Database.GetDbConnection();
        if (conn.State != System.Data.ConnectionState.Open) await conn.OpenAsync();
        await using var cmd = conn.CreateCommand();
        cmd.CommandText = sql;
        var v = await cmd.ExecuteScalarAsync();
        return v is null or DBNull ? default! : (T)Convert.ChangeType(v, Nullable.GetUnderlyingType(typeof(T)) ?? typeof(T), System.Globalization.CultureInfo.InvariantCulture);
    }

    /// <summary>1 point per piece of A46's shape that exists: OrderDate, its default, the four audit columns, UnitPrice(18,4), AutoGeneratedPrice(18,4), CK with 4, UUID in the lookup index.</summary>
    private static Task<int> Shape(DemandDbContext db) => Scalar<int>(db, @"
SELECT (SELECT COUNT(*) FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_orders') AND name = 'OrderDate')
 + (SELECT COUNT(*) FROM sys.default_constraints WHERE parent_object_id = OBJECT_ID('demand.purchase_orders') AND parent_column_id = COLUMNPROPERTY(OBJECT_ID('demand.purchase_orders'), 'OrderDate', 'ColumnId'))
 + (SELECT COUNT(*) FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_order_lines') AND name IN ('OriginalCurrencyId','OriginalCurrencyPrice','ExchangeRateUsed','ExchangeRateDate'))
 + (SELECT COUNT(*) FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_order_lines') AND name = 'UnitPrice' AND precision = 18 AND scale = 4)
 + (SELECT COUNT(*) FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_orders') AND name = 'AutoGeneratedPrice' AND precision = 18 AND scale = 4)
 + (SELECT COUNT(*) FROM sys.check_constraints WHERE name = 'CK_POLines_PriceSource' AND definition LIKE '%4%')
 + (SELECT COUNT(*) FROM sys.index_columns ic JOIN sys.indexes i ON i.object_id = ic.object_id AND i.index_id = ic.index_id
      JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
      WHERE i.name = 'IX_SupplierPricelists_Lookup' AND ic.is_included_column = 1 AND c.name = 'UUID')");

    private const int FullShape = 1 + 1 + 4 + 1 + 1 + 1 + 1;

    private static (string A45, string A46) Names(DemandDbContext db)
    {
        var all = db.Database.GetMigrations().ToList();
        return (all.Single(m => m.EndsWith("_A45_SupplierPricelists", StringComparison.Ordinal)),
                all.Single(m => m.EndsWith("_A46_PricingFoundation", StringComparison.Ordinal)));
    }

    [Fact]
    public async Task A46_0078_0079_goes_up_down_up_and_reruns_cleanly_on_a_database_that_already_has_it()
    {
        await using var db = NewContext();
        var (a45, a46) = Names(db);
        var migrator = db.GetService<IMigrator>();

        await migrator.MigrateAsync(a46);
        (await Shape(db)).Should().Be(FullShape);

        await migrator.MigrateAsync(a45);
        (await Shape(db)).Should().Be(1 /* the lookup index keeps the wider INCLUDE, harmless */);
        (await Scalar<int>(db, "SELECT COUNT(*) FROM sys.columns WHERE object_id = OBJECT_ID('demand.purchase_orders') AND name = 'OrderDate'")).Should().Be(0);

        await migrator.MigrateAsync(a46);
        (await Shape(db)).Should().Be(FullShape);

        // Drift: the history forgets A46 but everything it made is there (the shared database). It must run again cleanly.
        await db.Database.ExecuteSqlRawAsync(db.GetService<IHistoryRepository>().GetDeleteScript(a46));
        await migrator.MigrateAsync(a46);
        (await Shape(db)).Should().Be(FullShape);
    }

    [Fact]
    public async Task A46_0004_0006_0023_existing_POs_get_OrderDate_from_CreatedDate_and_keep_their_prices_and_a_re_run_never_overwrites_an_edited_date()
    {
        await using var db = NewContext();
        var (a45, a46) = Names(db);
        var migrator = db.GetService<IMigrator>();
        await migrator.MigrateAsync(a45);

        var org = Guid.NewGuid();
        await db.Database.ExecuteSqlRawAsync(
            "INSERT INTO demand.purchase_orders (UUID, OrganizationId, PoNumber, SupplierId, SupplierName, Status, TotalAmount, IsActive, IsDelete, CreatedBy, CreatedDate, Source) " +
            "VALUES (NEWID(), {0}, 'PO-OLD-1', NEWID(), 'Old', 'DRAFT', 12.35, 1, 0, 1, '2026-03-05T22:30:00', 'MANUAL')", org);
        await db.Database.ExecuteSqlRawAsync(
            "INSERT INTO demand.purchase_order_lines (UUID, OrganizationId, PurchaseOrderId, [LineNo], ItemDescription, Quantity, UnitPrice, LineTotal, QtyReceived, QtyInvoiced, RequiresInspection, PriceSource) " +
            "SELECT NEWID(), {0}, Id, 1, 'Old line', 1, 12.35, 12.35, 0, 0, 1, 3 FROM demand.purchase_orders WHERE PoNumber = 'PO-OLD-1'", org);

        await migrator.MigrateAsync(a46);

        await using var check = NewContext(org);
        var po = await check.PurchaseOrders.IgnoreQueryFilters().Include(p => p.Lines).SingleAsync(p => p.PoNumber == "PO-OLD-1");
        po.OrderDate.Should().Be(new DateTime(2026, 3, 5), "CAST(CreatedDate AS date) - the stored UTC date, not today");
        po.Lines.Single().UnitPrice.Should().Be(12.3500m, "12.35 reads as 12.3500 - no loss");
        po.Lines.Single().PriceSource.Should().Be(PriceSource.RFQ, "existing sources are untouched");
        po.Lines.Single().OriginalCurrencyId.Should().BeNull();

        // A buyer later changes the order date; the migration running again (history lost) must not reset it from CreatedDate.
        await check.Database.ExecuteSqlRawAsync("UPDATE demand.purchase_orders SET OrderDate = '2026-04-01' WHERE PoNumber = 'PO-OLD-1'");
        await check.Database.ExecuteSqlRawAsync(check.GetService<IHistoryRepository>().GetDeleteScript(a46));
        await migrator.MigrateAsync(a46);
        (await Scalar<string>(check, "SELECT CONVERT(varchar(10), OrderDate, 23) FROM demand.purchase_orders WHERE PoNumber = 'PO-OLD-1'")).Should().Be("2026-04-01");
    }

    [Fact]
    public async Task A46_0021_0034_0209_precision_the_price_source_check_and_the_conversion_audit_hold_in_the_real_database()
    {
        var org = Guid.NewGuid();
        await using var db = NewContext(org);
        await db.Database.MigrateAsync();

        var eur = Guid.NewGuid();
        var po = new PurchaseOrder
        {
            UUID = Guid.NewGuid(), TraceId = Guid.NewGuid(), OrganizationId = org, PoNumber = "PO-A46-1", SupplierId = Guid.NewGuid(), SupplierName = "S",
            CreatedBy = 1, CreatedDate = DateTime.UtcNow, OrderDate = new DateTime(2026, 10, 15), AutoGeneratedPrice = 12.3456m
        };
        po.Lines.Add(new PurchaseOrderLine
        {
            UUID = Guid.NewGuid(), OrganizationId = org, LineNo = 1, ItemDescription = "x", Quantity = 2m, UnitPrice = 12.3456m, LineTotal = 24.69m,
            PriceSource = PriceSource.Pricelist, SystemResolvedPrice = 12.3456m, OriginalCurrencyId = eur, OriginalCurrencyPrice = 11.3571m,
            ExchangeRateUsed = 1.08700001m, ExchangeRateDate = new DateTime(2026, 10, 15)
        });
        db.PurchaseOrders.Add(po);
        await db.SaveChangesAsync();

        await using var read = NewContext(org);
        var stored = await read.PurchaseOrders.Include(p => p.Lines).SingleAsync();
        stored.OrderDate.Should().Be(new DateTime(2026, 10, 15));
        stored.AutoGeneratedPrice.Should().Be(12.3456m);
        var line = stored.Lines.Single();
        (line.UnitPrice, line.SystemResolvedPrice).Should().Be((12.3456m, (decimal?)12.3456m));
        (line.OriginalCurrencyId, line.OriginalCurrencyPrice, line.ExchangeRateUsed, line.ExchangeRateDate)
            .Should().Be((eur, (decimal?)11.3571m, (decimal?)1.08700001m, (DateTime?)new DateTime(2026, 10, 15)));

        // CK_POLines_PriceSource: 0..4 accepted, 5 rejected.
        foreach (var ok in new[] { PriceSource.BlanketOrder, PriceSource.RFQ })
        {
            read.PurchaseOrderLines.IgnoreQueryFilters().Single().PriceSource = ok;
            await read.SaveChangesAsync();
        }
        await read.Database.ExecuteSqlRawAsync("UPDATE demand.purchase_order_lines SET PriceSource = 4");
        var reject = () => read.Database.ExecuteSqlRawAsync("UPDATE demand.purchase_order_lines SET PriceSource = 5");
        (await reject.Should().ThrowAsync<SqlException>()).WithMessage("*CK_POLines_PriceSource*");

        // The default for OrderDate on a row that names none.
        await read.Database.ExecuteSqlRawAsync(
            "INSERT INTO demand.purchase_orders (UUID, OrganizationId, PoNumber, SupplierId, SupplierName, Status, TotalAmount, IsActive, IsDelete, CreatedBy, CreatedDate, Source) " +
            "VALUES (NEWID(), {0}, 'PO-A46-2', NEWID(), 'S', 'DRAFT', 0, 1, 0, 1, SYSUTCDATETIME(), 'MANUAL')", org);
        (await Scalar<int>(read, "SELECT DATEDIFF(day, OrderDate, SYSUTCDATETIME()) FROM demand.purchase_orders WHERE PoNumber = 'PO-A46-2'")).Should().Be(0);

        read.Database.HasPendingModelChanges().Should().BeFalse("the hand-written SQL must produce the model the code maps (A46-0084)");
    }

    [Fact]
    public async Task Down_with_a_blanket_price_line_sets_it_to_Manual_so_the_old_check_can_hold()
    {
        await using var db = NewContext();
        var (a45, a46) = Names(db);
        var migrator = db.GetService<IMigrator>();
        await migrator.MigrateAsync(a46);
        await db.Database.ExecuteSqlRawAsync(
            "INSERT INTO demand.purchase_orders (UUID, OrganizationId, PoNumber, SupplierId, SupplierName, Status, TotalAmount, IsActive, IsDelete, CreatedBy, CreatedDate, Source, OrderDate) " +
            "VALUES (NEWID(), NEWID(), 'PO-RB', NEWID(), 'S', 'DRAFT', 0, 1, 0, 1, SYSUTCDATETIME(), 'MANUAL', SYSUTCDATETIME())");
        await db.Database.ExecuteSqlRawAsync(
            "INSERT INTO demand.purchase_order_lines (UUID, OrganizationId, PurchaseOrderId, [LineNo], ItemDescription, Quantity, UnitPrice, LineTotal, QtyReceived, QtyInvoiced, RequiresInspection, PriceSource) " +
            "SELECT NEWID(), NEWID(), Id, 1, 'b', 1, 4.5678, 4.57, 0, 0, 1, 4 FROM demand.purchase_orders WHERE PoNumber = 'PO-RB'");

        await migrator.MigrateAsync(a45);
        (await Scalar<int>(db, "SELECT PriceSource FROM demand.purchase_order_lines")).Should().Be(0);
        (await Scalar<decimal>(db, "SELECT UnitPrice FROM demand.purchase_order_lines")).Should().Be(4.57m, "narrowing back to 2dp rounds - documented in the rollback script");
    }
}
