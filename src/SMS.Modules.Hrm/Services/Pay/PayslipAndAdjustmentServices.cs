internal sealed record PayslipDocument(
    string OrganizationName, string RunNumber, DateOnly PeriodStart, DateOnly PeriodEnd, DateOnly PayDate, string Currency,
    string EmployeeNumber, string EmployeeName, string? Department, string? Designation, decimal WorkingDays, decimal PaidDays, decimal WorkedDays,
    IReadOnlyList<(string Name, decimal Amount)> Earnings, IReadOnlyList<(string Name, decimal Amount)> Deductions, IReadOnlyList<(string Name, decimal Amount)> EmployerContributions,
    decimal Gross, decimal TotalDeductions, decimal Net, decimal YtdGross, decimal YtdDeductions, decimal YtdNet, DateOnly YtdFrom);

/// <summary>Task 268. Through <see cref="PdfRenderGate"/> always: parallel QuestPDF renders garble bold text.</summary>
internal static class PayslipRenderer
{
    public static byte[] Render(PayslipDocument d)
    {
        QuestPDF.Settings.License ??= LicenseType.Community;
        var document = Document.Create(container => container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(32);
            page.DefaultTextStyle(x => x.FontSize(10));
            page.Header().Column(col =>
            {
                col.Item().Text(d.OrganizationName).FontSize(16).Bold();
                col.Item().Text($"Payslip {d.RunNumber}: {d.PeriodStart:dd MMM yyyy} to {d.PeriodEnd:dd MMM yyyy}, paid {d.PayDate:dd MMM yyyy}");
            });
            page.Content().PaddingVertical(12).Column(col =>
            {
                col.Spacing(10);
                col.Item().Table(t =>
                {
                    t.ColumnsDefinition(c => { c.RelativeColumn(); c.RelativeColumn(); });
                    t.Cell().Text($"Employee: {d.EmployeeName} ({d.EmployeeNumber})");
                    t.Cell().Text($"Department: {d.Department ?? "-"}");
                    t.Cell().Text($"Designation: {d.Designation ?? "-"}");
                    t.Cell().Text($"Days: {d.PaidDays:0.##} paid of {d.WorkingDays:0.##}, {d.WorkedDays:0.##} worked");
                });
                Amounts(col, "Earnings", d.Earnings, d.Currency);
                Amounts(col, "Deductions", d.Deductions, d.Currency);
                if (d.EmployerContributions.Count > 0) Amounts(col, "Employer contributions (not part of your pay)", d.EmployerContributions, d.Currency);
                col.Item().AlignRight().Text($"Gross {d.Gross:N2}   Deductions {d.TotalDeductions:N2}");
                col.Item().AlignRight().Text($"Net pay {d.Currency} {d.Net:N2}").FontSize(13).Bold();
                col.Item().PaddingTop(8).Text($"Year to date from {d.YtdFrom:dd MMM yyyy}: gross {d.YtdGross:N2}, deductions {d.YtdDeductions:N2}, net {d.YtdNet:N2}");
            });
            page.Footer().AlignCenter().Text("This payslip was generated by the system.").FontSize(8);
        }));
        return PdfRenderGate.Run(document.GeneratePdf);
    }

    private static void Amounts(ColumnDescriptor col, string title, IReadOnlyList<(string Name, decimal Amount)> rows, string currency)
    {
        col.Item().Text(title).Bold();
        col.Item().Table(t =>
        {
            t.ColumnsDefinition(c => { c.RelativeColumn(3); c.RelativeColumn(1); });
            foreach (var (name, amount) in rows)
            {
                t.Cell().Text(name);
                t.Cell().AlignRight().Text($"{amount:N2}");
            }
            if (rows.Count == 0)
            {
                t.Cell().Text("None");
                t.Cell().AlignRight().Text($"{0m:N2}");
            }
        });
    }
}

/// <summary>
/// Tasks 267–270. One immutable PDF per line, generated once from the line's snapshot. Generated lazily too, so a person can read a payslip without someone
/// having pressed "generate all". Only finalized runs; a reversed run's payslip stays on file but is no longer offered to the employee.
/// </summary>
internal sealed class PayslipService : HrmServiceBase, IPayslipService
{
    private static readonly string[] Issuable = [PayrollRunStatuses.Finalized, PayrollRunStatuses.Posted, PayrollRunStatuses.Paid];

    private readonly IHrmScopeService _scope;
    private readonly IHrmDocumentStore _documents;
    private readonly IOrganizationNameLookup? _names;

    public PayslipService(HrmDbContext db, IHrmScopeService scope, IHrmDocumentStore documents, IOrganizationNameLookup? names = null) : base(db)
    {
        _scope = scope;
        _documents = documents;
        _names = names;
    }

    public async Task<PayslipBulkResult> GenerateAllAsync(HrmCaller caller, Guid runUuid, CancellationToken ct = default)
    {
        var org = caller.OrganizationId;
        var run = await Db.PayrollRuns.IgnoreQueryFilters().AsNoTracking().FirstOrDefaultAsync(r => r.OrganizationId == org && r.Uuid == runUuid, ct) ?? throw new NotFoundException("Payroll run", runUuid);
        if (!Issuable.Contains(run.Status)) throw HrmErrors.Conflict("PAYROLL_NOT_FINALIZED", "Payslips exist once the run is finalized.");
        var lineIds = await Db.PayrollRunLines.IgnoreQueryFilters().AsNoTracking().Where(l => l.RunId == run.Id && l.OrganizationId == org && !l.IsBlocked).Select(l => new { l.Id, Has = l.Payslip != null }).ToListAsync(ct);
        var result = new PayslipBulkResult { AlreadyGenerated = lineIds.Count(l => l.Has) };
        foreach (var line in lineIds.Where(l => !l.Has))
        {
            await EnsureAsync(caller, line.Id, ct);
            result.Generated++;
        }
        return result;
    }

    public async Task<PayFile> GetForLineAsync(HrmCaller caller, Guid runUuid, Guid lineUuid, CancellationToken ct = default)
    {
        var org = caller.OrganizationId;
        var line = await Db.PayrollRunLines.IgnoreQueryFilters().AsNoTracking().Where(l => l.OrganizationId == org && l.Uuid == lineUuid && l.Run!.Uuid == runUuid)
            .Select(l => new { l.Id, l.EmployeeId, l.IsBlocked, l.Run!.Status }).FirstOrDefaultAsync(ct) ?? throw new NotFoundException("Payroll line", lineUuid);
        if (!await _scope.CanAccessAsync(caller, line.EmployeeId, ct)) throw new NotFoundException("Payroll line", lineUuid);
        if (line.IsBlocked || !(Issuable.Contains(line.Status) || line.Status == PayrollRunStatuses.Reversed)) throw HrmErrors.Conflict("PAYROLL_NOT_FINALIZED", "This line has no payslip.");
        return await ReadAsync(await EnsureAsync(caller, line.Id, ct));
    }

    public async Task<IReadOnlyList<PayslipSummaryModel>> ListOwnAsync(HrmCaller caller, int? year, CancellationToken ct = default)
    {
        var org = caller.OrganizationId;
        var employee = await _scope.RequireOwnEmployeeAsync(caller, ct);
        var query = Db.PayrollRunLines.IgnoreQueryFilters().AsNoTracking()
            .Where(l => l.OrganizationId == org && l.EmployeeId == employee.Id && !l.IsBlocked && Issuable.Contains(l.Run!.Status));
        if (year is { } y) query = query.Where(l => l.Run!.PeriodEnd.Year == y);
        var rows = await query.OrderByDescending(l => l.Run!.PeriodEnd)
            .Select(l => new { l.Id, l.Run!.RunNumber, l.Run.PeriodStart, l.Run.PeriodEnd, l.Net }).ToListAsync(ct);
        var result = new List<PayslipSummaryModel>();
        foreach (var r in rows)
        {
            var slip = await EnsureAsync(caller, r.Id, ct);
            result.Add(new PayslipSummaryModel { RunNumber = r.RunNumber, PeriodStart = r.PeriodStart, PeriodEnd = r.PeriodEnd, Net = r.Net, PayslipUuid = slip.Uuid });
        }
        return result;
    }

    public async Task<PayFile> GetPdfAsync(HrmCaller caller, Guid payslipUuid, CancellationToken ct = default)
    {
        var org = caller.OrganizationId;
        var row = await Db.Payslips.IgnoreQueryFilters().AsNoTracking().Where(p => p.OrganizationId == org && p.Uuid == payslipUuid)
            .Select(p => new { Slip = p, p.RunLine!.EmployeeId, p.RunLine.Run!.Status }).FirstOrDefaultAsync(ct) ?? throw new NotFoundException("Payslip", payslipUuid);
        var own = await _scope.OwnEmployeeIdAsync(caller, ct);
        var mine = own == row.EmployeeId && caller.Has(PermissionCodes.HRM_SELF_SERVICE) && row.Status != PayrollRunStatuses.Reversed;
        var asHr = caller.Has(PermissionCodes.HRM_PAYROLL_VIEW) && await _scope.CanAccessAsync(caller, row.EmployeeId, ct);
        if (!mine && !asHr) throw new NotFoundException("Payslip", payslipUuid);
        return await ReadAsync(row.Slip);
    }

    private async Task<PayFile> ReadAsync(Payslip slip)
    {
        var content = await _documents.ReadAsync(slip.AttachmentUuid) ?? throw new NotFoundException("The payslip file is missing.");
        return new PayFile { Content = content.Content, FileName = slip.FileName, ContentType = "application/pdf" };
    }

    /// <summary>Unique on the line: a concurrent request that generated it first wins and its file is the one kept.</summary>
    private async Task<Payslip> EnsureAsync(HrmCaller caller, int lineId, CancellationToken ct)
    {
        var existing = await Db.Payslips.IgnoreQueryFilters().AsNoTracking().FirstOrDefaultAsync(p => p.RunLineId == lineId && p.OrganizationId == caller.OrganizationId, ct);
        if (existing is not null) return existing;

        var document = await BuildDocumentAsync(caller.OrganizationId, lineId, ct);
        var lineUuid = await Db.PayrollRunLines.IgnoreQueryFilters().Where(l => l.Id == lineId).Select(l => l.Uuid).FirstAsync(ct);
        var pdf = PayslipRenderer.Render(document);
        var fileName = $"Payslip-{document.RunNumber}-{document.EmployeeNumber}.pdf";
        var attachment = await _documents.StorePdfAsync(caller, HrmAttachmentCodes.Payslip, lineUuid, fileName, pdf, PermissionCodes.HRM_PAYROLL_VIEW, ct);
        var slip = new Payslip { RunLineId = lineId, AttachmentUuid = attachment, FileName = fileName };
        Stamp(slip, caller, isNew: true);
        Db.Payslips.Add(slip);
        try
        {
            await Db.SaveChangesAsync(ct);
            return slip;
        }
        catch (DbUpdateException ex) when (IsDuplicate(ex))
        {
            Db.Entry(slip).State = EntityState.Detached;
            return await Db.Payslips.IgnoreQueryFilters().AsNoTracking().FirstAsync(p => p.RunLineId == lineId && p.OrganizationId == caller.OrganizationId, ct);
        }
    }

    internal async Task<PayslipDocument> BuildDocumentAsync(Guid org, int lineId, CancellationToken ct)
    {
        var line = await Db.PayrollRunLines.IgnoreQueryFilters().AsNoTracking().Include(l => l.Run).Include(l => l.Employee).Include(l => l.Components)
            .FirstAsync(l => l.Id == lineId && l.OrganizationId == org, ct);
        var run = line.Run!;
        // Year to date = this tax year up to and including this run. Pakistan's tax year starts 1 July, elsewhere 1 January (settings' country).
        var country = await Db.Settings.IgnoreQueryFilters().AsNoTracking().Where(s => s.OrganizationId == org).Select(s => s.CountryCode).FirstOrDefaultAsync(ct) ?? "PK";
        var end = run.PeriodEnd;
        var ytdFrom = country == "PK" ? new DateOnly(end.Month >= 7 ? end.Year : end.Year - 1, 7, 1) : new DateOnly(end.Year, 1, 1);
        var ytd = await Db.PayrollRunLines.IgnoreQueryFilters().AsNoTracking()
            .Where(l => l.OrganizationId == org && l.EmployeeId == line.EmployeeId && !l.IsBlocked && l.Run!.PeriodEnd >= ytdFrom && l.Run.PeriodEnd <= end
                && (Issuable.Contains(l.Run.Status) || l.RunId == run.Id))
            .Select(l => new { l.Gross, l.TotalDeductions, l.Net }).ToListAsync(ct);

        List<(string, decimal)> Rows(string type) => line.Components.Where(c => c.Type == type).OrderBy(c => c.Sequence)
            .GroupBy(c => new { c.Code, c.Sequence }).Select(g => (g.First().Name, g.Sum(c => c.Amount))).ToList();

        var name = _names is null ? null : await _names.GetNameAsync(org, ct);
        return new PayslipDocument(name ?? "Payslip", run.RunNumber, run.PeriodStart, run.PeriodEnd, run.PayDate, run.CurrencyCode, line.Employee!.EmployeeNumber, line.Employee.FullName,
            line.DepartmentName, line.DesignationName, line.WorkingDays, line.PaidDays, line.WorkedDays,
            Rows(SalaryComponentTypes.Earning), Rows(SalaryComponentTypes.Deduction), Rows(SalaryComponentTypes.EmployerContribution),
            line.Gross, line.TotalDeductions, line.Net, ytd.Sum(y => y.Gross), ytd.Sum(y => y.TotalDeductions), ytd.Sum(y => y.Net), ytdFrom);
    }
}

/// <summary>Tasks 275–277. One-off items a run picks up. Signed: a negative earning is a correction. Not deletable once a finalized run applied them.</summary>
internal sealed class PayrollAdjustmentService : HrmServiceBase, IPayrollAdjustmentService
{
    private readonly IHrmScopeService _scope;
    public PayrollAdjustmentService(HrmDbContext db, IHrmScopeService scope) : base(db) => _scope = scope;

    private IQueryable<PayrollAdjustment> Query(Guid org) => Db.PayrollAdjustments.IgnoreQueryFilters()
        .Include(a => a.Employee).Include(a => a.Run).Include(a => a.AppliedInRun).Where(a => a.OrganizationId == org);

    private static PayrollAdjustmentModel Map(PayrollAdjustment a) => new()
    {
        Uuid = a.Uuid, EmployeeUuid = a.Employee!.Uuid, EmployeeName = a.Employee.FullName, RunUuid = a.Run?.Uuid, ComponentCode = a.ComponentCode, Amount = a.Amount,
        Reason = a.Reason, AppliedInRunUuid = a.AppliedInRun?.Uuid
    };

    public async Task<IReadOnlyList<PayrollAdjustmentModel>> ListAsync(HrmCaller caller, Guid? employeeUuid, bool? pending, CancellationToken ct = default)
    {
        var scope = await _scope.GetAsync(caller, ct);
        var employees = _scope.Apply(Db.Employees, caller, scope);
        var query = Query(caller.OrganizationId).AsNoTracking().Where(a => employees.Any(e => e.Id == a.EmployeeId));
        if (employeeUuid is { } uuid) query = query.Where(a => a.Employee!.Uuid == uuid);
        if (pending == true) query = query.Where(a => a.AppliedInRunId == null);
        if (pending == false) query = query.Where(a => a.AppliedInRunId != null);
        var rows = await query.OrderByDescending(a => a.Id).ToListAsync(ct);
        return rows.Select(Map).ToList();
    }

    public async Task<PayrollAdjustmentModel> CreateAsync(HrmCaller caller, PayrollAdjustmentCreate request, CancellationToken ct = default)
    {
        var org = caller.OrganizationId;
        var employee = await _scope.RequireEmployeeAsync(caller, request.EmployeeUuid, ct);
        var code = HrmValidate.Code(request.ComponentCode);
        var component = await Db.SalaryComponents.IgnoreQueryFilters().AsNoTracking().FirstOrDefaultAsync(c => c.OrganizationId == org && c.Code == code, ct);
        if (component is null || component.Type is not (SalaryComponentTypes.Earning or SalaryComponentTypes.Deduction))
            throw HrmErrors.Bad("ADJUSTMENT_COMPONENT_INVALID", $"{code} is not an earning or deduction component.");
        if (request.Amount == 0m || decimal.Round(request.Amount, 2) != request.Amount) throw HrmErrors.Bad("ADJUSTMENT_AMOUNT_INVALID", "An amount cannot be zero and has at most 2 decimals.");

        int? runId = null;
        if (request.RunUuid is { } runUuid)
        {
            var run = await Db.PayrollRuns.IgnoreQueryFilters().AsNoTracking().FirstOrDefaultAsync(r => r.OrganizationId == org && r.Uuid == runUuid, ct) ?? throw new NotFoundException("Payroll run", runUuid);
            if (run.Status is not (PayrollRunStatuses.Draft or PayrollRunStatuses.Calculated)) throw HrmErrors.Conflict("PAYROLL_STATUS", "An adjustment can target a run only before review.");
            runId = run.Id;
        }
        var row = new PayrollAdjustment { EmployeeId = employee.Id, RunId = runId, ComponentCode = code, Amount = request.Amount, Reason = HrmValidate.Name(request.Reason, 500, "Reason") };
        Stamp(row, caller, isNew: true);
        Db.PayrollAdjustments.Add(row);
        await Db.SaveChangesAsync(ct);
        return Map(await Query(org).AsNoTracking().FirstAsync(a => a.Id == row.Id, ct));
    }

    public async Task DeleteAsync(HrmCaller caller, Guid uuid, CancellationToken ct = default)
    {
        var row = await Query(caller.OrganizationId).FirstOrDefaultAsync(a => a.Uuid == uuid, ct) ?? throw new NotFoundException("Payroll adjustment", uuid);
        if (!await _scope.CanAccessAsync(caller, row.EmployeeId, ct)) throw new NotFoundException("Payroll adjustment", uuid);
        if (row.AppliedInRunId is not null) throw HrmErrors.Conflict("ADJUSTMENT_APPLIED", "This adjustment has been applied by a run.");
        if (row.ExpenseClaimId is not null) throw HrmErrors.Conflict("ADJUSTMENT_APPLIED", "This adjustment belongs to an expense claim.");
        Db.PayrollAdjustments.Remove(row);
        await SaveAsync(ct, "This adjustment");
    }
}
