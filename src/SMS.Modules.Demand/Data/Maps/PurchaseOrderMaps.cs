using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using SMS.Modules.Demand.Domain;

namespace SMS.Modules.Demand.Data.Maps;

internal sealed class PurchaseOrderMap : IEntityTypeConfiguration<PurchaseOrder>
{
    public void Configure(EntityTypeBuilder<PurchaseOrder> b)
    {
        b.ToTable("purchase_orders");
        b.HasKey(x => x.Id);
        b.Property(x => x.Id).ValueGeneratedOnAdd();
        b.Property(x => x.UUID).IsRequired();
        b.HasIndex(x => x.UUID).IsUnique();
        b.Property(x => x.TraceId).IsRequired().ValueGeneratedOnAdd().HasDefaultValueSql("NEWSEQUENTIALID()");
        b.HasIndex(x => x.TraceId);
        b.Property(x => x.PoNumber).HasMaxLength(20).IsRequired();
        // Composite, not global — each org generates its own PO number sequence.
        b.HasIndex(x => new { x.OrganizationId, x.PoNumber }).IsUnique();
        b.Property(x => x.Title).HasMaxLength(200);
        b.Property(x => x.SupplierName).HasMaxLength(200).IsRequired();
        b.Property(x => x.Status).HasMaxLength(20).HasDefaultValue("DRAFT");
        b.Property(x => x.TotalAmount).HasColumnType("decimal(18,2)");
        // A46 M9/M10 — the order date (date part); the column default is today (UTC), existing rows were backfilled from CreatedDate.
        b.Property(x => x.OrderDate).HasColumnType("date").HasDefaultValueSql("CAST(SYSUTCDATETIME() AS date)");
        b.Property(x => x.Notes).HasMaxLength(500);
        b.Property(x => x.InternalNotes).HasMaxLength(2000);
        b.Property(x => x.DeliveryWarehouseName).HasMaxLength(150);
        b.Property(x => x.SupplierContactMobile).HasMaxLength(20);
        b.Property(x => x.IsActive).HasDefaultValue(true);
        b.Property(x => x.OrganizationId).IsRequired();
        b.HasIndex(x => x.OrganizationId);

        // A29-P5-01 §6.3/§17.2.
        b.Property(x => x.Source).HasMaxLength(20).HasDefaultValue("MANUAL");
        b.Property(x => x.AutoGeneratedQty).HasColumnType("decimal(18,4)");
        b.Property(x => x.AutoGeneratedPrice).HasColumnType("decimal(18,4)"); // A46 E-6: compared with the 4dp line price
        b.HasIndex(x => new { x.OrganizationId, x.TraceId });
        b.HasIndex(x => new { x.LinkedSoId, x.LinkedSoLineId });

        // A35 D-10/D-11 — currency + the rate locked at APPROVED (null = not locked) and the total in the purchase base.
        b.Property(x => x.ExchangeRate).HasColumnType("decimal(18,10)");
        b.Property(x => x.TotalAmountBase).HasColumnType("decimal(18,4)");

        b.HasMany(x => x.Lines)
         .WithOne(x => x.PurchaseOrder)
         .HasForeignKey(x => x.PurchaseOrderId)
         .OnDelete(DeleteBehavior.Cascade);

        b.HasMany(x => x.PrLinks)
         .WithOne(x => x.PurchaseOrder)
         .HasForeignKey(x => x.PurchaseOrderId)
         .OnDelete(DeleteBehavior.Cascade);
    }
}

internal sealed class PurchaseOrderLineMap : IEntityTypeConfiguration<PurchaseOrderLine>
{
    public void Configure(EntityTypeBuilder<PurchaseOrderLine> b)
    {
        b.ToTable("purchase_order_lines", t => t.HasCheckConstraint("CK_POLines_PriceSource", "[PriceSource] IN (0, 1, 2, 3, 4)"));
        b.HasKey(x => x.Id);
        b.Property(x => x.Id).ValueGeneratedOnAdd();
        b.Property(x => x.UUID).IsRequired();
        b.HasIndex(x => x.UUID).IsUnique();
        b.Property(x => x.ItemDescription).HasMaxLength(300).IsRequired();
        b.Property(x => x.Specification).HasMaxLength(500);
        b.Property(x => x.UnitOfMeasure).HasMaxLength(20);
        b.Property(x => x.Quantity).HasColumnType("decimal(18,4)");
        b.Property(x => x.UnitPrice).HasColumnType("decimal(18,4)"); // A46 M4 / E-6: was (18,2); prices are stored at 4dp
        b.Property(x => x.LineTotal).HasColumnType("decimal(18,2)");
        b.Property(x => x.LineDiscountPct).HasColumnType("decimal(5,2)");
        b.Property(x => x.QtyReceived).HasColumnType("decimal(18,4)").HasDefaultValue(0m);
        b.Property(x => x.QtyInvoiced).HasColumnType("decimal(18,4)").HasDefaultValue(0m);
        b.Property(x => x.BudgetCode).HasMaxLength(50);
        b.Property(x => x.WarehouseName).HasMaxLength(150);
        b.Property(x => x.RequiresInspection).HasDefaultValue(true);
        b.Property(x => x.UnitPriceBase).HasColumnType("decimal(18,4)"); // A35 D-10
        b.Property(x => x.LineTotalBase).HasColumnType("decimal(18,4)");
        // A45 M2 — the price source of the line (default 0 = Manual) and the pricelist figures behind it.
        b.Property(x => x.PriceSource).HasConversion<byte>().HasDefaultValue(PriceSource.Manual);
        b.Property(x => x.SystemResolvedPrice).HasColumnType("decimal(18,4)");
        b.Property(x => x.PriceOverrideReason).HasMaxLength(500);
        // A46 M8 — the pricelist row's own currency/price and the rate used when the price was converted into the PO's currency.
        b.Property(x => x.OriginalCurrencyPrice).HasColumnType("decimal(18,4)");
        b.Property(x => x.ExchangeRateUsed).HasColumnType("decimal(18,8)");
        b.Property(x => x.ExchangeRateDate).HasColumnType("date");
        b.Property(x => x.OrganizationId).IsRequired();
        b.HasIndex(x => x.OrganizationId);
    }
}

