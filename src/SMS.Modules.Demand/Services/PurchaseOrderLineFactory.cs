using SMS.Modules.Demand.Domain;
using SMS.Modules.Demand.Models;

namespace SMS.Modules.Demand.Services;

/// <summary>Where a purchase order line is being created from (A46 C5 table). Informational for the factory's rules; recorded nowhere.</summary>
internal enum LineOrigin
{
    /// <summary>Typed on the PO form / sent through the API: the client's price claim is verified, a missing price is resolved.</summary>
    Manual,
    /// <summary>Purchase requisition conversion: priced from the pricelist; the requisition estimate is only the fallback.</summary>
    PurchaseRequest,
    /// <summary>Awarded RFQ / quotation: the quoted price is contractual (source RFQ), the resolver is not called.</summary>
    Rfq,
    /// <summary>A blanket-order call-off: the locked price is used (source BlanketOrder 4). No blanket-order entity exists yet.</summary>
    BlanketOrder,
    /// <summary>Raised by the system: back-to-back / drop-ship / MIR deficit, production shortage, reorder point.</summary>
    AutoGenerated,
    /// <summary>CSV / spreadsheet import: a price &gt; 0 is kept as Manual, otherwise the pricelist is tried.</summary>
    Import,
    /// <summary>The quantity moved off another line onto a new PO (for another supplier).</summary>
    Split,
    /// <summary>A reissued PO's copy of a line: everything about its price is carried over unchanged.</summary>
    Clone
}

/// <summary>What the factory builds a line from. Only <see cref="ItemDescription"/>, <see cref="Quantity"/> are mandatory.</summary>
internal sealed class CreateLineInput
{
    public LineOrigin Origin { get; init; } = LineOrigin.Manual;
    public int LineNo { get; init; }

    public Guid? SourcePrLineUuid { get; init; }
    public Guid? VariantUuid { get; init; }
    public string ItemDescription { get; init; } = string.Empty;
    public string? Specification { get; init; }
    public string? UnitOfMeasure { get; init; }
    public decimal Quantity { get; init; }
    public decimal? LineDiscountPct { get; init; }
    public DateTime? RequiredDate { get; init; }
    public string? LineNotes { get; init; }
    public string? BudgetCode { get; init; }
    public Guid? WarehouseId { get; init; }
    public string? WarehouseName { get; init; }
    public bool RequiresInspection { get; init; } = true;

    /// <summary>The price the caller typed / sent (0 = none: the server prices the line).</summary>
    public decimal UnitPrice { get; init; }

    /// <summary>Spec C5: a price already known to a trusted caller (RFQ quote, blanket order, import). With <see cref="SuppliedPriceSource"/> it is used as-is; the resolver is not called.</summary>
    public decimal? SuppliedPrice { get; init; }
    public PriceSource? SuppliedPriceSource { get; init; }
    public string? SuppliedOverrideReason { get; init; }

    /// <summary>The price used when nothing resolves and the caller gave none (a requisition's estimate, a variant's catalogue price).</summary>
    public decimal? FallbackPrice { get; init; }

    /// <summary>An API client's unverified claim about the price source (A45 D-10). Null = none (a legacy client / an internal caller).</summary>
    public PriceClaim? Claim { get; init; }

    /// <summary>The stored line this one rebuilds (a PO edit replaces every line): lets the middleware see a quantity / date / product change.</summary>
    public PreviousLineState? Previous { get; init; }

    /// <summary>Clone: the line to copy. Its price source, resolved price, pricelist row and conversion audit come across untouched.</summary>
    public PurchaseOrderLine? CopyFrom { get; init; }

    public static CreateLineInput From(
        CreatePoLineRequest r, int lineNo, decimal? fallbackPrice = null, PreviousLineState? previous = null, bool systemRaised = false)
    {
        // A line the system raised, with no source claim, hands its price over as the fallback: the pricelist is tried first.
        var autoPriced = systemRaised && r.PriceSource is null;
        return new()
        {
        Origin = autoPriced ? LineOrigin.AutoGenerated : LineOrigin.Manual, LineNo = lineNo, SourcePrLineUuid = r.SourcePrLineUuid, VariantUuid = r.VariantUuid,
        ItemDescription = r.ItemDescription, Specification = r.Specification, UnitOfMeasure = r.UnitOfMeasure, Quantity = r.Quantity,
        LineDiscountPct = r.LineDiscountPct, RequiredDate = r.RequiredDate, LineNotes = r.LineNotes, BudgetCode = r.BudgetCode,
        WarehouseId = r.WarehouseId, WarehouseName = r.WarehouseName, RequiresInspection = r.RequiresInspection,
        UnitPrice = autoPriced ? 0m : r.UnitPrice, FallbackPrice = fallbackPrice, Previous = previous,
        Claim = new PriceClaim
        {
            Source = r.PriceSource, SystemResolvedPrice = r.SystemResolvedPrice, PricelistUuid = r.SupplierPricelistUuid,
            OverrideReason = r.PriceOverrideReason
        }
        };
    }
}

/// <summary>The stored state of a line a PO edit is rebuilding.</summary>
internal sealed record PreviousLineState(Guid? VariantUuid, decimal Quantity, DateTime? RequiredDate);

internal sealed class PurchaseOrderLineResult
{
    public PurchaseOrderLine Line { get; init; } = null!;
    /// <summary>True when the line's price stands on a pricelist row, an awarded RFQ or a blanket order (i.e. a person need not price it).</summary>
    public bool PriceWasResolved { get; init; }
    /// <summary>Null when priced; otherwise why the line still needs a price.</summary>
    public string? WarningMessage { get; init; }
    /// <summary>A46-0152 - what the pricing middleware did (null when the line's price was supplied/copied and the middleware did not run).</summary>
    internal LinePricingOutcome? Outcome { get; init; }
}

/// <summary>
/// A46 C5 / BR-29 - the ONLY way a purchase order line is created in SMS. Every path (manual entry, requisition conversion,
/// quotation / RFQ, system-raised deficits, split, reissue) goes through here so the price resolution runs and the price-source
/// fields are set the same way everywhere; an architectural test fails the build of any other construction site.
/// The caller adds the returned line to the PO.
/// </summary>
internal interface IPurchaseOrderLineFactory
{
    Task<PurchaseOrderLineResult> CreateLineAsync(PurchaseOrder po, CreateLineInput input, CancellationToken ct = default);
}

internal sealed class PurchaseOrderLineFactory : IPurchaseOrderLineFactory
{
    private readonly IPurchaseOrderLinePricingMiddleware _pricing;

    public PurchaseOrderLineFactory(IPurchaseOrderLinePricingMiddleware pricing) => _pricing = pricing;

    public async Task<PurchaseOrderLineResult> CreateLineAsync(PurchaseOrder po, CreateLineInput input, CancellationToken ct = default)
    {
        var line = new PurchaseOrderLine
        {
            UUID               = Guid.NewGuid(),
            LineNo             = input.LineNo,
            SourcePrLineUuid   = input.SourcePrLineUuid,
            VariantUuid        = input.VariantUuid,
            ItemDescription    = input.ItemDescription,
            Specification      = input.Specification,
            UnitOfMeasure      = input.UnitOfMeasure,
            Quantity           = input.Quantity,
            UnitPrice          = input.UnitPrice,
            LineDiscountPct    = input.LineDiscountPct,
            RequiredDate       = input.RequiredDate,
            LineNotes          = input.LineNotes,
            BudgetCode         = input.BudgetCode,
            WarehouseId        = input.WarehouseId,
            WarehouseName      = input.WarehouseName,
            RequiresInspection = input.RequiresInspection
        };

        string? warning = null;
        LinePricingOutcome? middlewareOutcome = null;
        if (input.CopyFrom is { } source)
        {
            // Reissue: the price and everything behind it travel with the line (no resolver, no claim).
            line.UnitPrice             = source.UnitPrice;
            line.PriceSource           = source.PriceSource;
            line.SystemResolvedPrice   = source.SystemResolvedPrice;
            line.SupplierPricelistUuid = source.SupplierPricelistUuid;
            line.PriceOverrideReason   = source.PriceOverrideReason;
            line.OriginalCurrencyId    = source.OriginalCurrencyId;
            line.OriginalCurrencyPrice = source.OriginalCurrencyPrice;
            line.ExchangeRateUsed      = source.ExchangeRateUsed;
            line.ExchangeRateDate      = source.ExchangeRateDate;
        }
        else if (input.SuppliedPriceSource is { } suppliedSource
                 && (suppliedSource is PriceSource.RFQ or PriceSource.BlanketOrder
                     || (suppliedSource == PriceSource.Manual && input.SuppliedPrice is > 0m)))
        {
            // A price the caller already holds (E-7: only a trusted internal caller can say RFQ / BlanketOrder here).
            line.UnitPrice           = PurchaseOrderLinePricingMiddleware.RoundPrice(input.SuppliedPrice ?? input.UnitPrice);
            line.PriceSource         = suppliedSource;
            line.PriceOverrideReason = suppliedSource == PriceSource.Manual ? null : input.SuppliedOverrideReason;
        }
        else
        {
            var previous = input.Previous;
            var context = new LineChangeContext
            {
                IsNew                = previous is null,
                Claim                = input.Claim ?? new PriceClaim(),
                FallbackPrice        = input.FallbackPrice,
                ProductChanged       = previous is not null && previous.VariantUuid != input.VariantUuid,
                QuantityChanged      = previous is not null && previous.Quantity != input.Quantity,
                // A new date is a change; a line sent with no date again is not (the server may have defaulted the stored one from the lead time).
                DeliveryDateChanged  = previous is not null && input.RequiredDate is { } sentDate && previous.RequiredDate?.Date != sentDate.Date,
                PreviousQuantity     = previous?.Quantity,
                PreviousDeliveryDate = previous?.RequiredDate
            };
            var outcome = await _pricing.ApplyPricingAsync(line, po, context, ct);
            warning = outcome.Warning;
            middlewareOutcome = outcome;
        }

        line.LineTotal = PurchaseOrderLinePricingMiddleware.LineTotal(line.Quantity, line.UnitPrice);

        var priced = line.PriceSource != PriceSource.Manual;
        return new PurchaseOrderLineResult
        {
            Line             = line,
            PriceWasResolved = priced,
            WarningMessage   = priced ? null : warning ?? NoPriceWarning(line),
            Outcome          = middlewareOutcome
        };
    }

    private static string? NoPriceWarning(PurchaseOrderLine line) =>
        line.UnitPrice > 0m ? null : $"No price for {(string.IsNullOrWhiteSpace(line.ItemDescription) ? "this line" : line.ItemDescription)}. Enter the price manually.";

    /// <summary>BR-30 - folds the results of a batch of lines created together into the summary shown to the buyer.</summary>
    public static PricingSummary Summarize(IEnumerable<PurchaseOrderLineResult> results)
    {
        var list = results.ToList();
        var priced = list.Count(r => r.PriceWasResolved);
        return new PricingSummary
        {
            TotalLines    = list.Count,
            PricedCount   = priced,
            UnpricedCount = list.Count - priced,
            Warnings      = list.Where(r => !r.PriceWasResolved && !string.IsNullOrWhiteSpace(r.WarningMessage)).Select(r => r.WarningMessage!).ToList()
        };
    }
}

